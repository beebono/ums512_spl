#!/usr/bin/env python3
# Regenerate chipram/nand_spl/cfw_pinmap.h from u-boot's pin_init() tables.
# Build pinmap.o and sprd_uart_matrix_cfg.o in a u-boot O= dir
#   make ... O=$OUT board/spreadtrum/ums512_1h10/{pinmap,sprd_uart_matrix_cfg}.o
# then run this from $OUT/board/spreadtrum/ums512_1h10 > cfw_pinmap.h
import subprocess, struct, sys
def sect(obj, name):
    out = subprocess.run(["aarch64-linux-gnu-objcopy", "-O", "binary", "--only-section="+name, obj, "/dev/stdout"], capture_output=True).stdout
    return out
pm = sect("pinmap.o", ".rodata.pinmap"); ad = sect("pinmap.o", ".rodata.adie_pinmap")
up = sect("sprd_uart_matrix_cfg.o", ".data.uport")
w = lambda b, o: struct.unpack_from("<I", b, o)[0]
assert len(pm) == 342*8 and len(ad) == 5*8, (len(pm), len(ad))
cfg = cfg1 = None
if w(up, 8):
    cfg = (w(up,1268)<<20)|(w(up,956)<<16)|(w(up,644)<<10)|(w(up,332)<<4)|(w(up,1892)<<28)|(w(up,1580)<<24)|w(up,20)
    cfg1 = (w(up,2828)<<9)|(w(up,2516)<<5)|w(up,2204)
regs = [(w(pm, i*8), w(pm, i*8+4)) for i in range(342)]
if cfg is not None:
    regs += [(4, cfg), (8, cfg1)]	# UART_MATRIX_MTX_CFG, _CFG1
vals = sorted(set(v for _, v in regs))
assert len(vals) <= 128 and all(r % 4 == 0 and r < 0x800 for r, _ in regs)
print("/* Generated by scripts/gen_cfw_pinmap.py from u-boot-ums512\n * board/spreadtrum/ums512_1h10/pinmap.c (pin_init()). Do not edit.\n *\n * cfw_pinmap[]: (word offset from 0x32450000) << 7 | index into\n * cfw_pinvals[], written in u-boot's order. cfw_adie_pinmap[]: ADI\n * offsets from 0x32120000, OR-set like sci_adi_set(). */")
print("static const uint32_t cfw_pinvals[] = {")
for i in range(0, len(vals), 4):
    print("\t" + " ".join("0x%08x," % v for v in vals[i:i+4]))
print("};\n\nstatic const uint16_t cfw_pinmap[] = {")
ent = ["0x%04x," % ((r // 4) << 7 | vals.index(v)) for r, v in regs]
for i in range(0, len(ent), 8):
    print("\t" + " ".join(ent[i:i+8]))
print("};\n\nstatic const struct cfw_pin cfw_adie_pinmap[] = {")
for i in range(5): print("\t{ 0x%04x, 0x%08x }," % (w(ad,i*8)+0x480, w(ad,i*8+4)))
print("};")
